_FORMAT_SPEC = """\
Тебе нужно построить двусторонний детерминированный конечный автомат (2DFA) для языка, \
заданного текстовым описанием ниже.

Определение 2DFA. Входная строка w = a1 ... aℓ записана на ленте между метками начала ⊢ и \
конца ⊣: ⊢ a1 ... aℓ ⊣. Автомат начинает в своём единственном начальном состоянии, головка \
стоит на ⊢. На каждом шаге по текущему состоянию и символу под головкой (в том числе по ⊢ или \
⊣) функция переходов задаёт новое состояние и направление движения: 1 — направо, -1 — налево. \
Функция переходов частичная: если перехода нет, автомат отвергает. Строка принимается, если \
головка приходит на метку конца ⊣ в принимающем состоянии. Если автомат зацикливается, уходит \
налево с ⊢ или направо с ⊣ — строка не принимается.

Формат вывода — строго только сам автомат в следующем виде, без markdown-разметки и без \
пояснений:
n
m
<начальное состояние>
<принимающие состояния через пробел>
<состояние> <символ> <состояние> <направление>
...

Где:
- n — число состояний (состояния нумеруются от 0 до n-1)
- m — размер алфавита (без учёта меток ⊢ и ⊣)
- каждая строка перехода — это четвёрка "откуда символ куда направление", по одной строке на \
переход; направление — 1 (направо) или -1 (налево)
- номер символа — это его индекс в алфавите, заданном ниже (индексация с 0, в том порядке, \
в котором символы перечислены); метка начала ⊢ имеет номер m, метка конца ⊣ — номер m+1\
"""

_FEW_SHOT_EXAMPLE = """\
Пример формата (иллюстрация, не связана с задачей ниже): 2DFA для языка "последний символ \
равен 1" над алфавитом {0, 1} (индекс 0 -> '0', 1 -> '1', ⊢ -> 2, ⊣ -> 3). Автомат едет \
направо до ⊣, разворачивается, проверяет последний символ и возвращается на ⊣:
3
2
0
2
0 2 0 1
0 0 0 1
0 1 0 1
0 3 1 -1
1 1 2 1\
"""


def build_prompt_2dfa(description: str, alphabet: tuple[str, ...]) -> str:
    m = len(alphabet)
    symbols = [f"{i} -> {symbol!r}" for i, symbol in enumerate(alphabet)] + [f"{m} -> '⊢'", f"{m + 1} -> '⊣'"]
    return (
        f"{_FORMAT_SPEC}\n\n"
        f"{_FEW_SHOT_EXAMPLE}\n\n"
        f"Алфавит для задачи ниже (символ -> индекс): {', '.join(symbols)}\n\n"
        f"Описание языка: {description}\n\n"
        "Выведи только 2DFA в указанном формате, без каких-либо пояснений до или после."
    )
