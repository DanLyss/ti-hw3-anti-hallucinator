_FORMAT_SPEC = """\
Тебе нужно построить конечный автомат (NFA или DFA) для языка, заданного текстовым \
описанием ниже.

Формат вывода — строго только сам автомат в следующем виде, без markdown-разметки и без \
пояснений:
n
m
<стартовые состояния через пробел>
<финальные состояния через пробел>
<состояние> <символ> <состояние>
...

Где:
- n — число состояний (состояния нумеруются от 0 до n-1)
- m — размер алфавита
- каждая строка перехода — это тройка "откуда символ куда", по одной строке на переход
- номер символа — это его индекс в алфавите, заданном ниже (индексация с 0, в том \
порядке, в котором символы перечислены)\
"""

_FEW_SHOT_EXAMPLE = """\
Пример формата (иллюстрация, не связана с задачей ниже). Алфавит примера: {0, 1} \
(индекс 0 -> '0', индекс 1 -> '1'):
3
2
0
1
0 0 1
0 0 2
0 1 2
1 0 2
2 1 2
2 0 0\
"""


def build_prompt(description: str, alphabet: tuple[str, ...]) -> str:
    alphabet_line = ", ".join(f"{i} -> {symbol!r}" for i, symbol in enumerate(alphabet))
    return (
        f"{_FORMAT_SPEC}\n\n"
        f"{_FEW_SHOT_EXAMPLE}\n\n"
        f"Алфавит для задачи ниже (символ -> индекс): {alphabet_line}\n\n"
        f"Описание языка: {description}\n\n"
        "Выведи только автомат в указанном формате, без каких-либо пояснений до или после."
    )
